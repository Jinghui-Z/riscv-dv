static inline uint32_t ai_backend_sm4ed_ref(uint8_t value, unsigned bs)
{
    const uint32_t sbox = ai_backend_sm4_sbox[value];
    const uint32_t linear = sbox ^ (sbox << 8U) ^ (sbox << 2U) ^
        (sbox << 18U) ^ ((sbox & 0x3fU) << 26U) ^
        ((sbox & 0xc0U) << 10U);

    return ai_backend_rotl32(linear, 8U * bs);
}

static inline uint32_t ai_backend_sm4ks_ref(uint8_t value, unsigned bs)
{
    const uint32_t sbox = ai_backend_sm4_sbox[value];
    const uint32_t linear = sbox ^ ((sbox & 0x07U) << 29U) ^
        ((sbox & 0xfeU) << 7U) ^ ((sbox & 0x01U) << 23U) ^
        ((sbox & 0xf8U) << 13U);

    return ai_backend_rotl32(linear, 8U * bs);
}

bool ai_micro_backend_bku_zero_clz_ctz_cpop_matrix_corner()
{
    TEST_START();

    uint64_t clz_result;
    uint64_t ctz_result;
    uint64_t cpop_result;
    uint64_t clzw_result;
    uint64_t ctzw_result;
    uint64_t cpopw_result;

    goto_priv(PRIV_M);
    asm volatile(
        ".option push\n\t"
        ".option arch,+zbb\n\t"
        "clz %0, zero\n\t"
        "ctz %1, zero\n\t"
        "cpop %2, zero\n\t"
        "clzw %3, zero\n\t"
        "ctzw %4, zero\n\t"
        "cpopw %5, zero\n\t"
        ".option pop\n\t"
        : "=r"(clz_result), "=r"(ctz_result), "=r"(cpop_result),
          "=r"(clzw_result), "=r"(ctzw_result), "=r"(cpopw_result)
        :
        : "memory");

    TEST_ASSERT("BKU zero-source CLZ/CTZ return XLEN while CPOP returns zero",
        clz_result == 64ULL && ctz_result == 64ULL &&
        cpop_result == 0ULL);
    TEST_ASSERT("BKU zero-source word count operations return 32/32/0",
        clzw_result == 32ULL && ctzw_result == 32ULL &&
        cpopw_result == 0ULL);

    TEST_END();
}

bool ai_micro_backend_crypto_aes_sm4_sbox_exhaustive_matrix_corner()
{
    TEST_START();

    uint64_t mismatch_count = 0ULL;
    uint64_t signature = 0x6b657973626f7831ULL;

    goto_priv(PRIV_M);
    TEST_SETUP_EXCEPT();
    for (unsigned input = 0; input < 256U; ++input) {
        const uint8_t value = (uint8_t)input;
        const uint64_t source = ai_backend_repeat_byte(value);
        const uint64_t aes_forward = ai_backend_repeat_byte(
            ai_backend_aes_sbox_ref(value));
        const uint64_t aes_inverse = ai_backend_repeat_byte(
            ai_backend_aes_inverse_sbox_ref(value));
        const uint32_t key_word =
            (uint32_t)ai_backend_repeat_byte(ai_backend_aes_sbox_ref(value));
        const uint64_t key_rnum0 =
            ((uint64_t)(key_word ^ 0x01U) << 32U) |
            (uint64_t)(key_word ^ 0x01U);

        const uint64_t aes_es = ai_backend_aes64es(source, source);
        const uint64_t aes_esm = ai_backend_aes64esm(source, source);
        const uint64_t aes_ds = ai_backend_aes64ds(source, source);
        const uint64_t aes_dsm = ai_backend_aes64dsm(source, source);
        const uint64_t aes_ks0 = ai_backend_aes64ks1i_rnum0(source);
        const uint64_t aes_ks10 = ai_backend_aes64ks1i_rnum10(source);

        mismatch_count += aes_es != aes_forward;
        mismatch_count += aes_esm != aes_forward;
        mismatch_count += aes_ds != aes_inverse;
        mismatch_count += aes_dsm != aes_inverse;
        mismatch_count += aes_ks0 != key_rnum0;
        mismatch_count += aes_ks10 != aes_forward;

        const uint64_t sm4ed[4] = {
            ai_backend_sm4ed_bs0(0ULL, source),
            ai_backend_sm4ed_bs1(0ULL, source),
            ai_backend_sm4ed_bs2(0ULL, source),
            ai_backend_sm4ed_bs3(0ULL, source)
        };
        const uint64_t sm4ks[4] = {
            ai_backend_sm4ks_bs0(0ULL, source),
            ai_backend_sm4ks_bs1(0ULL, source),
            ai_backend_sm4ks_bs2(0ULL, source),
            ai_backend_sm4ks_bs3(0ULL, source)
        };

        for (unsigned bs = 0; bs < 4U; ++bs) {
            mismatch_count += sm4ed[bs] != ai_backend_sext32(
                ai_backend_sm4ed_ref(value, bs));
            mismatch_count += sm4ks[bs] != ai_backend_sext32(
                ai_backend_sm4ks_ref(value, bs));
            signature ^= ai_backend_rotl32((uint32_t)sm4ed[bs],
                (input + bs) & 31U);
            signature = (signature << 7U) | (signature >> 57U);
            signature ^= sm4ks[bs] + aes_es + aes_ds + aes_ks10;
        }
    }

    TEST_ASSERT("all 256 AES forward, inverse and key-schedule S-box inputs and all SM4 byte-select S-box inputs execute without exception",
        excpt.triggered == false);
    TEST_ASSERT("AES and SM4 exhaustive S-box instruction outputs match independent software reference transforms",
        mismatch_count == 0ULL && signature != 0ULL,
        "mismatches=%llu signature=0x%llx",
        (unsigned long long)mismatch_count,
        (unsigned long long)signature);

    TEST_END();
}
