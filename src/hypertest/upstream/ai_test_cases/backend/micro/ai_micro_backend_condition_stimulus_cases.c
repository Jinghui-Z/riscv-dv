static uint8_t ai_backend_aes_sbox_ref(uint8_t value)
{
    return ai_backend_aes_sbox[value];
}

static uint8_t ai_backend_aes_inverse_sbox_ref(uint8_t value)
{
    return ai_backend_aes_inverse_sbox[value];
}

static inline uint64_t ai_backend_repeat_byte(uint8_t value)
{
    return 0x0101010101010101ULL * value;
}

static inline uint32_t ai_backend_rotl32(uint32_t value, unsigned shamt)
{
    shamt &= 31U;
    if (shamt == 0U) {
        return value;
    }
    return (value << shamt) | (value >> (32U - shamt));
}

static inline uint64_t ai_backend_sext32(uint32_t value)
{
    return (uint64_t)(int64_t)(int32_t)value;
}

#define AI_BACKEND_CRYPTO_RR_HELPER(name_, arch_, insn_) \
static inline uint64_t name_(uint64_t lhs, uint64_t rhs) \
{ \
    uint64_t result; \
    asm volatile( \
        ".option push\n\t" \
        ".option arch," arch_ "\n\t" \
        insn_ " %0, %1, %2\n\t" \
        ".option pop\n\t" \
        : "=r"(result) : "r"(lhs), "r"(rhs) : "memory"); \
    return result; \
